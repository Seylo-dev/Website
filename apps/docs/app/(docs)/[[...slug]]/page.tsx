import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { createRelativeLink } from "fumadocs-ui/mdx";
import {
  DocsBody,
  DocsDescription,
  DocsPage,
  DocsTitle,
  EditOnGitHub,
  MarkdownCopyButton,
  ViewOptionsPopover,
} from "fumadocs-ui/layouts/docs/page";
import { OpenAPIPage } from "@/components/api-page";
import { getMDXComponents } from "@/components/mdx";
import { brand, editUrl } from "@/lib/brand";
import { appName, getPageImageUrl, getPageMarkdownUrl } from "@/lib/shared";
import { source } from "@/lib/source";

export default async function Page(props: { params: Promise<{ slug?: string[] }> }) {
  const params = await props.params;
  const page = source.getPage(params.slug);
  if (!page) notFound();

  // Generated from openapi.json: no MDX body, the OpenAPI UI renders the whole operation.
  if (page.data.type === "openapi") {
    return (
      <DocsPage full>
        <DocsTitle>{page.data.title}</DocsTitle>
        <DocsBody>
          <OpenAPIPage {...page.data.getOpenAPIPageProps()} />
        </DocsBody>
      </DocsPage>
    );
  }

  const MDX = page.data.body;
  const markdownUrl = getPageMarkdownUrl(page).url;
  const sourceUrl = editUrl(`content/docs/${page.path}`);
  // The CLI reference is generated by scripts/gen-cli-reference.ts, so it gets no edit link.
  const generated = page.path === "reference/cli.mdx";

  return (
    <DocsPage toc={page.data.toc} full={page.data.full}>
      <DocsTitle>{page.data.title}</DocsTitle>
      <DocsDescription className="mb-0">{page.data.description}</DocsDescription>
      <div className="flex flex-row items-center gap-2 border-b pb-6">
        <MarkdownCopyButton markdownUrl={markdownUrl} />
        <ViewOptionsPopover markdownUrl={markdownUrl} githubUrl={sourceUrl} />
        {generated ? null : <EditOnGitHub href={sourceUrl} />}
      </div>
      <DocsBody>
        <MDX
          components={getMDXComponents({
            // Lets pages link to each other by relative file path too.
            a: createRelativeLink(source, page),
          })}
        />
      </DocsBody>
    </DocsPage>
  );
}

export function generateStaticParams() {
  return source.generateParams();
}

export async function generateMetadata(props: { params: Promise<{ slug?: string[] }> }): Promise<Metadata> {
  const params = await props.params;
  const page = source.getPage(params.slug);
  if (!page) notFound();

  const isHome = page.slugs.length === 0;
  return {
    title: isHome ? { absolute: appName } : page.data.title,
    description: page.data.description ?? `${brand.name} documentation`,
    alternates: { canonical: page.url },
    openGraph: { images: getPageImageUrl(page).url },
  };
}
