// Writes content/docs/reference/cli.mdx from the `seylo` binary's own help, so the reference
// never drifts from the commands that shipped. Hidden commands (used by the installer and the
// updater) stay out because cobra leaves them out of --help.
//
//   bun run cli:reference <path to a seylo binary>
//
// Take the binary from a release of the app repo (see README.md) or build it from the app repo
// (go/cmd/seylo). The command tree is the same on every OS; only Windows builds lack the node
// commands, so use a Linux or macOS build.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const binary = process.argv[2];
if (!binary) {
  console.error("usage: bun run cli:reference <path to a seylo binary>");
  process.exit(1);
}
const out = resolve(import.meta.dirname, "../content/docs/reference/cli.mdx");

interface Command {
  path: string[];
  help: string;
  children: Command[];
}

function help(path: string[]): string {
  return execFileSync(binary as string, [...path, "--help"], { encoding: "utf8" }).replace(/\s+$/, "");
}

/** Names listed under the "... Commands:" headings of a help text, with their heading. */
function listed(text: string): { group: string; name: string }[] {
  const found: { group: string; name: string }[] = [];
  let group: string | null = null;
  for (const line of text.split("\n")) {
    if (/^[A-Z].*ommands.*:$/.test(line)) {
      group = line.slice(0, -1);
      continue;
    }
    if (line.trim() === "") {
      group = null;
      continue;
    }
    const name = line.trim().split(/\s+/)[0];
    if (group && name && name !== "help" && name !== "completion") found.push({ group, name });
  }
  return found;
}

function walk(path: string[]): Command {
  const text = help(path);
  return { path, help: text, children: listed(text).map(({ name }) => walk([...path, name])) };
}

/** Splits a help text into its description and the usage block, without the global flags. */
function sections(text: string): { description: string; usage: string } {
  const at = text.indexOf("Usage:");
  const description = (at === -1 ? "" : text.slice(0, at)).trim();
  let usage = at === -1 ? text : text.slice(at);
  usage = usage.replace(/\n\nGlobal Flags:[\s\S]*?(?=\n\n|$)/, "");
  usage = usage.replace(/\n\nUse "[^"]+" for more information about a command\.$/, "");
  return { description, usage: usage.trim() };
}

function globalFlags(text: string): string {
  const match = /Flags:\n([\s\S]*?)(?:\n\n|$)/.exec(text);
  return (match?.[1] ?? "")
    .split("\n")
    .filter((line) => !line.includes("--help"))
    .join("\n");
}

/** Help prose as MDX: `<`, `>`, `{` and `}` outside backticks would be read as JSX. */
function mdxProse(text: string): string {
  const entities: Record<string, string> = { "<": "&lt;", ">": "&gt;", "{": "&#123;", "}": "&#125;" };
  return text
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith("`") ? part : part.replace(/[<>{}]/g, (c) => entities[c] ?? c)))
    .join("");
}

function render(cmd: Command, depth: number): string {
  const { description, usage } = sections(cmd.help);
  const title = `${"#".repeat(depth)} \`seylo ${cmd.path.join(" ")}\``;
  const parts = [title, "", mdxProse(description), "", "```text", usage, "```", ""];
  for (const child of cmd.children) parts.push(render(child, depth + 1));
  return parts.join("\n");
}

const root = walk([]);
const groups = new Map<string, Command[]>();
for (const { group, name } of listed(root.help)) {
  const cmd = root.children.find((c) => c.path[0] === name);
  if (!cmd) continue;
  groups.set(group, [...(groups.get(group) ?? []), cmd]);
}

const groupTitles: Record<string, string> = {
  "Node commands (run on a server)": "Node commands",
  "Panel commands (run anywhere)": "Panel commands",
  "Additional Commands": "Other commands",
};
const groupIntros: Record<string, string> = {
  "Node commands (run on a server)":
    "Run these as root on a node. They talk to the local agent through its socket in `/var/lib/seylo/run/` and to systemd. Off Linux they answer that they run on a Linux server.",
  "Panel commands (run anywhere)":
    "Run these on a laptop, in CI or on a node, after `seylo login` or with `SEYLO_PANEL_URL` and `SEYLO_TOKEN` set. They use the panel's HTTP API with an API key. Services are named `<project>/<service>`, a bare name when it is unique, or an id. See [Command line](/guides/command-line).",
  "Additional Commands": "",
};

const body = [
  "---",
  "title: CLI reference",
  "description: Every seylo command and flag, generated from the binary's own help output.",
  "---",
  "",
  "{/* Generated by scripts/gen-cli-reference.ts from `seylo --help`. Do not edit by hand: rebuild the binary and run the script again. */}",
  "",
  "One binary, `seylo`, is the node agent (`seylo agent`, started by systemd), the node's command line and the command line for your laptop. Release builds exist for Linux, macOS and Windows; see [Command line](/guides/command-line) for installing it on a laptop.",
  "",
  "## Global flags",
  "",
  "Every command takes these:",
  "",
  "```text",
  globalFlags(sections(root.help).usage),
  "```",
  "",
  "`seylo <command> --help` prints the same help as below.",
  "",
];
for (const [group, commands] of groups) {
  body.push(`## ${groupTitles[group] ?? group}`, "");
  const intro = groupIntros[group];
  if (intro) body.push(intro, "");
  for (const cmd of commands) body.push(render(cmd, 3));
}

writeFileSync(
  out,
  `${body
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()}\n`,
);
console.log(`wrote ${out}`);
